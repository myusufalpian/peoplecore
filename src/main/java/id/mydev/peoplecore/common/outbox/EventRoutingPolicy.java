package id.mydev.peoplecore.common.outbox;

import java.util.Set;

public final class EventRoutingPolicy {
    private static final Set<String> METADATA_ONLY=Set.of(
        "EMPLOYEE_CREATE", "EMPLOYEE_UPDATE", "ASSIGNMENT_ADD", "ASSIGNMENT_REVISE", "EMPLOYMENT_UPDATE",
        "INVITATION_ACTIVATE", "ACCOUNT_OFFBOARD", "ACCOUNT_REBIND", "ACCOUNT_REHIRE", "ACCOUNT_RESTORE",
        "PROFILE_CREATE", "PROFILE_EDIT", "PROFILE_MASTER_CORRECT", "PROFILE_RULE_PUBLISH", "PROFILE_RULE_ACTIVATE",
        "ATTENDANCE_CLOCK", "ATTENDANCE_CORRECTION_CREATE", "ATTENDANCE_CORRECTION_EDIT", "ATTENDANCE_CORRECTION_DISCARD",
        "ATTENDANCE_RULE_PUBLISH", "ATTENDANCE_RULE_ACTIVATE",
        "SCHEDULE_PUBLISH", "SCHEDULE_ASSIGN", "CALENDAR_PUBLISH", "CALENDAR_ASSIGN",
        "LEAVE_OPENING", "LEAVE_ADJUSTMENT", "LEAVE_REQUEST_CREATE", "LEAVE_REQUEST_EDIT", "LEAVE_REQUEST_DISCARD",
        "LEAVE_RULE_PUBLISH", "LEAVE_RULE_ACTIVATE",
        "REIMBURSEMENT_CREATE", "REIMBURSEMENT_EDIT", "REIMBURSEMENT_CATEGORY_PUBLISH",
        "DOCUMENT_CREATE", "DOCUMENT_RESERVE_UPLOAD", "DOCUMENT_FINALIZE"
    );
    private static final Set<String> NOTIFICATION_EVENTS=Set.of(
        "INVITATION_ISSUE", "INVITATION_REISSUE",
        "PROFILE_SUBMIT", "PROFILE_RESUBMIT", "PROFILE_WITHDRAW", "PROFILE_APPROVE", "PROFILE_REJECT",
        "PROFILE_RETURN", "PROFILE_REASSIGN", "PROFILE_ROUTE_RETRY",
        "ATTENDANCE_CORRECTION_SUBMIT", "ATTENDANCE_CORRECTION_RESUBMIT", "ATTENDANCE_CORRECTION_WITHDRAW",
        "ATTENDANCE_CORRECTION_APPROVE", "ATTENDANCE_CORRECTION_REJECT", "ATTENDANCE_CORRECTION_RETURN",
        "ATTENDANCE_CORRECTION_REASSIGN", "ATTENDANCE_CORRECTION_ROUTE_RETRY",
        "LEAVE_REQUEST_SUBMIT", "LEAVE_REQUEST_RESUBMIT", "LEAVE_REQUEST_WITHDRAW", "LEAVE_REQUEST_APPROVE",
        "LEAVE_REQUEST_REJECT", "LEAVE_REQUEST_RETURN", "LEAVE_REQUEST_REASSIGN", "LEAVE_REQUEST_RETRY_ROUTE",
        "LEAVE_CANCELLATION_CREATE", "LEAVE_CANCELLATION_WITHDRAW", "LEAVE_CANCELLATION_APPROVE",
        "LEAVE_CANCELLATION_REJECT", "LEAVE_CANCELLATION_REASSIGN", "LEAVE_CANCELLATION_RETRY_ROUTE",
        "REIMBURSEMENT_SUBMIT", "REIMBURSEMENT_RESUBMIT", "REIMBURSEMENT_WITHDRAW", "REIMBURSEMENT_APPROVE",
        "REIMBURSEMENT_REJECT", "REIMBURSEMENT_RETURN", "REIMBURSEMENT_REASSIGN", "REIMBURSEMENT_RETRY_ROUTE",
        "REIMBURSEMENT_RECORD_PAYMENT", "REIMBURSEMENT_CORRECT_PAYMENT",
        "PAYSLIP_PUBLISHED", "EXPORT_READY", "EXPORT_FAILED", "EXPORT_EXPIRED", "EXPORT_INVALIDATED"
    );

    private EventRoutingPolicy() { }

    public static boolean metadataOnly(String eventType) {
        return eventType!=null && METADATA_ONLY.contains(eventType);
    }

    public static boolean notificationEvent(String eventType) {
        return eventType!=null && NOTIFICATION_EVENTS.contains(eventType);
    }

    public static boolean knownAsync(String eventType) {
        return "EXPORT_REQUESTED".equals(eventType) || notificationEvent(eventType);
    }
}
