CREATE TABLE clock_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    occurrence_id BIGINT NOT NULL REFERENCES attendance_occurrence(id),
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    action VARCHAR(3) NOT NULL CHECK (action IN ('IN', 'OUT')),
    received_at TIMESTAMPTZ NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_clock_event_action UNIQUE (occurrence_id, action)
);
CREATE INDEX idx_clock_employee_acceptance ON clock_event(employee_id, accepted_at);
CREATE TABLE attendance_effective_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    occurrence_id BIGINT NOT NULL REFERENCES attendance_occurrence(id),
    predecessor_id UUID REFERENCES attendance_effective_revision(public_id),
    in_at TIMESTAMPTZ NOT NULL,
    out_at TIMESTAMPTZ,
    source_id UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_attendance_effective_order CHECK (out_at IS NULL OR out_at > in_at),
    CONSTRAINT uq_effective_predecessor UNIQUE (predecessor_id)
);
CREATE INDEX idx_attendance_effective_occurrence ON attendance_effective_revision(occurrence_id, id DESC);
CREATE TABLE attendance_correction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    employee_id BIGINT NOT NULL REFERENCES employees(id),
    employee_public_id UUID NOT NULL,
    work_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('DRAFT','PENDING','RETURNED','DISCARDED','WITHDRAWN','APPROVED','REJECTED')),
    proposed_in TIMESTAMPTZ NOT NULL,
    proposed_out TIMESTAMPTZ,
    reason VARCHAR(2000) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    active_revision_id UUID,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX uq_attendance_open_correction ON attendance_correction(employee_id,work_date)
    WHERE status IN ('DRAFT','PENDING','RETURNED');
CREATE TABLE attendance_correction_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    correction_id BIGINT NOT NULL REFERENCES attendance_correction(id),
    occurrence_id BIGINT NOT NULL REFERENCES attendance_occurrence(id),
    baseline_id UUID REFERENCES attendance_effective_revision(public_id),
    proposed_in TIMESTAMPTZ NOT NULL,
    proposed_out TIMESTAMPTZ,
    reason VARCHAR(2000) NOT NULL,
    organization_assignment_id UUID,
    org_unit VARCHAR(128),
    original_reviewer_id BIGINT REFERENCES user_accounts(id),
    created_at TIMESTAMPTZ NOT NULL,
    CHECK (proposed_out IS NULL OR proposed_out > proposed_in)
);
ALTER TABLE attendance_correction ADD CONSTRAINT fk_attendance_correction_revision
    FOREIGN KEY(active_revision_id) REFERENCES attendance_correction_revision(public_id);
CREATE TABLE attendance_correction_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    revision_id UUID NOT NULL REFERENCES attendance_correction_revision(public_id),
    reviewer_id BIGINT NOT NULL REFERENCES user_accounts(id),
    previous_assignment_id UUID REFERENCES attendance_correction_assignment(public_id),
    reason VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_attendance_assignment_revision ON attendance_correction_assignment(revision_id,id DESC);
CREATE TABLE attendance_correction_decision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    revision_id UUID NOT NULL REFERENCES attendance_correction_revision(public_id),
    assignment_id UUID NOT NULL REFERENCES attendance_correction_assignment(public_id),
    reviewer_id BIGINT NOT NULL REFERENCES user_accounts(id),
    decision VARCHAR(16) NOT NULL CHECK(decision IN ('APPROVED','REJECTED','RETURNED')),
    reason VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_attendance_revision_decision UNIQUE(revision_id)
);
CREATE FUNCTION reject_attendance_evidence_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Attendance evidence is immutable' USING ERRCODE='42501';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_clock_evidence_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON clock_event
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
CREATE TRIGGER trg_effective_evidence_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON attendance_effective_revision
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
CREATE TRIGGER trg_correction_revision_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON attendance_correction_revision
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
CREATE TRIGGER trg_correction_assignment_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON attendance_correction_assignment
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
CREATE TRIGGER trg_correction_decision_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON attendance_correction_decision
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();

CREATE TABLE attendance_rule_set (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE attendance_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    rule_set_id UUID NOT NULL REFERENCES attendance_rule_set(public_id),
    priority INTEGER NOT NULL,
    org_unit VARCHAR(128),
    designated_hr_id BIGINT REFERENCES user_accounts(id),
    UNIQUE(rule_set_id,public_id)
);
CREATE TABLE attendance_rule_activation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    rule_set_id UUID NOT NULL REFERENCES attendance_rule_set(public_id),
    reason VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);
CREATE FUNCTION seal_attendance_rule_set() RETURNS trigger AS $$
BEGIN
    IF TG_OP <> 'UPDATE' OR OLD.published OR NOT NEW.published
        OR NEW.id<>OLD.id OR NEW.public_id<>OLD.public_id OR NEW.created_at<>OLD.created_at THEN
        RAISE EXCEPTION 'Published attendance rules are immutable' USING ERRCODE='42501';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_attendance_rule_set_immutable BEFORE UPDATE OR DELETE ON attendance_rule_set
    FOR EACH ROW EXECUTE FUNCTION seal_attendance_rule_set();
CREATE TRIGGER trg_attendance_rule_set_no_truncate BEFORE TRUNCATE ON attendance_rule_set
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
CREATE FUNCTION guard_attendance_rule_insert() RETURNS trigger AS $$
DECLARE sealed BOOLEAN;
BEGIN
    SELECT published INTO sealed FROM attendance_rule_set WHERE public_id=NEW.rule_set_id FOR UPDATE;
    IF sealed IS DISTINCT FROM FALSE THEN
        RAISE EXCEPTION 'Published attendance rules are immutable' USING ERRCODE='42501';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_attendance_rule_no_sealed_insert BEFORE INSERT ON attendance_rule
    FOR EACH ROW EXECUTE FUNCTION guard_attendance_rule_insert();
CREATE TRIGGER trg_attendance_rule_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON attendance_rule
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
CREATE TRIGGER trg_attendance_activation_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON attendance_rule_activation
    FOR EACH STATEMENT EXECUTE FUNCTION reject_attendance_evidence_mutation();
