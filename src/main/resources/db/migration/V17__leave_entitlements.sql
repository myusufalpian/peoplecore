 half_units_per_day INTEGER NOT NULL CHECK(half_units_per_day=2),
 period_basis VARCHAR(16) NOT NULL CHECK(period_basis='CALENDAR_YEAR'),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
