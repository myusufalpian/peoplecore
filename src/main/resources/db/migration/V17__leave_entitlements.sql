CREATE TABLE leave_account (
 employee_id BIGINT PRIMARY KEY REFERENCES employees(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE leave_period (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 employee_id BIGINT NOT NULL REFERENCES leave_account(employee_id),
 policy_revision_id BIGINT NOT NULL DEFAULT 1 REFERENCES leave_policy_revision(id),
 period_year INTEGER NOT NULL CHECK (period_year BETWEEN 1900 AND 9998),
 UNIQUE(employee_id, period_year)
);
CREATE TABLE leave_ledger (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id UUID NOT NULL UNIQUE,
 period_id BIGINT NOT NULL REFERENCES leave_period(id),
 entry_type VARCHAR(20) NOT NULL CHECK(entry_type IN ('OPENING','ADJUSTMENT','CONSUMPTION','REVERSAL')),
 business_reference VARCHAR(200) NOT NULL,
 source_reference VARCHAR(200) NOT NULL,
 half_units INTEGER NOT NULL CHECK(half_units <> 0),
 request_public_id UUID,
 request_revision INTEGER,
 original_entry_id BIGINT UNIQUE REFERENCES leave_ledger(id),
 source VARCHAR(200) NOT NULL,
 reason VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(period_id, entry_type, business_reference),
 CHECK((entry_type = 'ADJUSTMENT') OR half_units > 0),
 CHECK((entry_type IN ('CONSUMPTION','REVERSAL')) = (request_public_id IS NOT NULL AND request_revision IS NOT NULL)),
 CHECK((entry_type = 'REVERSAL') = (original_entry_id IS NOT NULL)),
 CHECK(entry_type IN ('CONSUMPTION','REVERSAL') OR (request_public_id IS NULL AND request_revision IS NULL)),
 CHECK(entry_type <> 'OPENING' OR business_reference = 'OPENING')
);
CREATE TABLE leave_reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 period_id BIGINT NOT NULL REFERENCES leave_period(id),
 request_public_id UUID NOT NULL,
 request_revision INTEGER NOT NULL CHECK(request_revision > 0),
 half_units INTEGER NOT NULL CHECK(half_units > 0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(request_public_id, request_revision)
);
CREATE FUNCTION seal_leave_ledger() RETURNS trigger AS $$
BEGIN
 RAISE EXCEPTION 'Leave ledger is append-only' USING ERRCODE = '42501';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_leave_ledger_immutable BEFORE UPDATE OR DELETE ON leave_ledger
 FOR EACH ROW EXECUTE FUNCTION seal_leave_ledger();
CREATE TRIGGER trg_leave_ledger_no_truncate BEFORE TRUNCATE ON leave_ledger
 FOR EACH STATEMENT EXECUTE FUNCTION seal_leave_ledger();

CREATE UNIQUE INDEX uk_leave_opening_period ON leave_ledger(period_id) WHERE entry_type='OPENING';
CREATE UNIQUE INDEX uk_leave_consumption_revision ON leave_ledger(request_public_id,request_revision) WHERE entry_type='CONSUMPTION';

CREATE TRIGGER trg_leave_policy_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON leave_policy_revision
 FOR EACH STATEMENT EXECUTE FUNCTION seal_leave_ledger();
CREATE TRIGGER trg_leave_period_immutable BEFORE UPDATE OR DELETE OR TRUNCATE ON leave_period
 FOR EACH STATEMENT EXECUTE FUNCTION seal_leave_ledger();
